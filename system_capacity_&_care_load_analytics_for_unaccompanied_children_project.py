import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

#dataset Loading
df = pd.read_csv("/content/HHS_Unaccompanied_Alien_Children_Program.csv")

#First five rows
df.head()

# Last Five rows
df.tail()

#shape
df.shape

#Columns
df.columns

df.info()

#Statistical summary
df.describe()

#Check Missing Values
df.isnull().sum()

df.isnull().all(axis=1).sum()

df =df.dropna()

df.shape

df.isnull().sum()

df['Date'] = pd.to_datetime(df['Date'])
df = df.sort_values('Date')

print(df.head())

df.columns.tolist()

df['Children in CBP custody'] = pd.to_numeric(df['Children in CBP custody'].astype(str).str.replace(',', ''), errors='coerce')

df['Children in HHS Care'] = pd.to_numeric(df['Children in HHS Care'].astype(str).str.replace(',', ''), errors='coerce')

#Total system load
df['Total Load'] = df['Children in CBP custody'] + df['Children in HHS Care']

print(df[['Date', 'Total Load']].head())

#Net daily intake Calculation
df['Net Intake'] = df['Children transferred out of CBP custody'] - df['Children discharged from HHS Care']

print(df[['Date', 'Net Intake']].head())

#growth Rate Calculation
df['Growth Rate'] = df['Total Load'].pct_change() * 100

print(df[['Date', 'Total Load', 'Growth Rate']].head(10))

#Day Average
df['7 Day Average'] = df['Total Load'].rolling(7).mean()

print(df[['Date', 'Total Load', '7 Day Average']].tail(10))

df['14 Day Average'] = df['Total Load'].rolling(14).mean()

print(df[['Date', '14 Day Average']].tail(10))

#Backlog Analysis
df['Backlog'] = df['Net Intake'].rolling(7).sum()

print(df[['Date', 'Net Intake', 'Backlog']].tail(10))

"""**KPI Calculations**"""

#Total Children Under Care
print("Total Children Under Care:", df['Total Load'].iloc[-1])

# Avg care load
print("Average Care Load:", df['Total Load'].mean())

#Maximum care load
print("Maximum Care Load:", df['Total Load'].max())

#Total Net Intake
print("Total Net Intake:", df['Net Intake'].sum())

#Care Load Volality
print("Care Load Volatility:", df['Total Load'].diff().std())

"""**Graphs**"""

